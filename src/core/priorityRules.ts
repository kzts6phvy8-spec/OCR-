/** 比べやすい形にする: 全角半角をそろえ、括弧書き・空白・読点などを除く */
function simplify(text: string): string {
  return text
    .normalize("NFKC")
    .replace(/\([^()]*\)/g, "")
    .replace(/[\s、,。・/&]/g, "")
    .replace(/度毎に|毎に/g, "度に");
}

// 長い条件から順に比べる (「撃破された後」より「敵部隊が撃破された後」を先に)
const TABLE = Object.entries(RULES)
  .flatMap(([priority, conditions]) => conditions.map((c) => ({ priority, key: simplify(c) })))
  .sort((a, b) => b.key.length - a.key.length);

/**
 * 覚醒スキルの効果文の書き出し (発動条件) から発動優先度を判断する。
 * 一覧にない条件なら空文字 (推測では埋めない)。
 */
export function inferPriorityFromCondition(effect: string | null | undefined): string {
  // 先頭の【覚醒】などの見出しは飛ばす
  const text = simplify((effect ?? "").replace(/^\s*[【[][^】\]]*[】\]]\s*/, ""));
  if (!text) return "";
  return TABLE.find((r) => text.startsWith(r.key))?.priority ?? "";
}
