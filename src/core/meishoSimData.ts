/**
 * 図鑑の武将に当たる、シミュレーターに直接渡した名将修行の追加天賦 (無ければ null)。
 * 勢力と名前で合わせる。同じ勢力に同じ名前が 2 人いる名将 (江姫・前田利家) は、通常/特異でも合わせる
 */
export function simMeishoTalents(w: Pick<Warlord, "faction" | "name" | "is_special">): MeishoTalent[] | null {
  const same = SIM_MEISHO.filter((m) => m.faction === w.faction && m.name === w.name);
  const hit = same.length > 1 ? same.find((m) => m.special === w.is_special) : same[0];
  return hit ? toTalents(hit) : null;
}

/** シミュレーターのデータのうち、図鑑のどの武将にも当たらない名将 (図鑑に未登録) */
export function simMeishoNotIn(warlords: Pick<Warlord, "faction" | "name" | "is_special">[]): { faction: string; name: string; special: boolean; talents: MeishoTalent[] }[] {
  return SIM_MEISHO.filter((m) => {
    const same = warlords.filter((w) => w.faction === m.faction && w.name === m.name);
    if (same.length === 0) return true;
    const twins = SIM_MEISHO.filter((x) => x.faction === m.faction && x.name === m.name).length > 1;
    return twins && !same.some((w) => w.is_special === m.special);
  }).map((m) => ({ faction: m.faction, name: m.name, special: m.special, talents: toTalents(m) }));
}

/** 効果の文を比べやすくする (書き方の揺れ: 戦場/戦闘・状態・記号・空白) */
const loose = (s: string) =>
  s
    .normalize("NFKC")
    .replace(/戦場/g, "戦闘")
    .replace(/状態/g, "")
    .replace(/自身の自身の/g, "自身の")
    .replace(/[\s、,.。()（）「」【】・:：を]/g, "");
const numbersOf = (s: string) => (s.normalize("NFKC").match(/\d+/g) ?? []).sort().join(",");
const bigrams = (s: string) => {
  const out = new Set<string>();
  for (let i = 0; i < s.length - 1; i++) out.add(s.slice(i, i + 2));
  return out;
};

/** 2 つの効果の文が、はっきり別の効果か (数値が違う、または文がほとんど似ていない) */
export function clearlyDifferentEffect(a: string, b: string): boolean {
  if (numbersOf(a) !== numbersOf(b)) return true;
  const x = bigrams(loose(a));
  const y = bigrams(loose(b));
  if (x.size === 0 || y.size === 0) return false;
  let same = 0;
  for (const g of x) if (y.has(g)) same++;
  return (2 * same) / (x.size + y.size) < 0.4;
}

/**
 * 名将修行の画面で読んだ追加天賦 (丸と効果) が、この武将のものではありえないか。
 * シミュレーターに直接渡したデータがある名将で、同じ丸の効果がはっきり違えば、別の名将の画面
 */
export function contradictsSimMeisho(w: Pick<Warlord, "faction" | "name" | "is_special">, read: MeishoTalent | null | undefined): boolean {
  if (!read) return false;
  const sim = simMeishoTalents(w)?.find((t) => t.rank === read.rank && t.slot === read.slot);
  return Boolean(sim && clearlyDifferentEffect(sim.effect, read.effect));
}

/** この丸のこの効果を持つ、シミュレーターのデータの名将の数 (少ないほど、その名将らしさの手がかりになる) */
function sharedCount(rank: string, slot: string, effect: string): number {
  const i = MEISHO_SLOTS.findIndex((s) => s.rank === rank && s.slot === slot);
  if (i < 0) return Infinity;
  return SIM_MEISHO.filter((m) => !clearlyDifferentEffect(m.effects[i], effect)).length;
}

/**
 * 同じ名将の名将修行の画面 (カードの絵が同じ画面) で読んだ追加天賦が、シミュレーターのデータの名将と合うか。
 *  - "contradict": どれかの丸の効果がはっきり違う (この名将の画面ではない)
 *  - "match": 食い違いが無く、その名将らしい (ほかの名将には 3 人以下しかない) 効果が 1 つ以上合う
 *  - "none": シミュレーターのデータが無い、または全員共通の効果しか読めていない (手がかりにならない)
 */
export function simEvidence(w: Pick<Warlord, "faction" | "name" | "is_special">, reads: MeishoTalent[]): "contradict" | "match" | "none" {
  const sim = simMeishoTalents(w);
  if (!sim) return "none";
  let distinctive = 0;
  for (const r of reads) {
    const t = sim.find((x) => x.rank === r.rank && x.slot === r.slot);
    if (!t) continue;
    if (clearlyDifferentEffect(t.effect, r.effect)) return "contradict";
    if (sharedCount(r.rank, r.slot, r.effect) <= 3) distinctive++;
  }
  return distinctive > 0 ? "match" : "none";
}
